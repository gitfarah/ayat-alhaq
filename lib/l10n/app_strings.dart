/// Lightweight app-chrome localization: Arabic (default), English and
/// Deutsch. Quran content and the reading surfaces themselves stay
/// Arabic by design — this covers navigation, home, and settings.
///
/// Usage: `final t = L10n.of(context); Text(t('tabIndex'))`.
class L10n {
  final String code;
  const L10n(this.code);

  /// Rebuilds the caller whenever the (effective) language changes —
  /// but only when called during build, where that's valid. Dozens of
  /// call sites use `L10n.of(context)` at the top of an event handler
  /// (onTap/onLongPress bodies, async methods that open a dialog or
  /// snackbar) purely to read the current strings once; they never
  /// needed to watch, but `context.watch` outside build throws
  /// Provider's own debug assertion before the dialog/sheet/snackbar
  /// ever appears — which is exactly what broke every long-press menu
  /// and audio control in the app (found 2026-08-02). Falling back to
  /// `context.read` is the fix Provider's own assertion message
  /// recommends; doing it here once is far safer than hand-editing the
  /// ~30 call sites, which stay correct automatically either way.
  static L10n of(BuildContext context) {
    SettingsService settings;
    try {
      settings = context.watch<SettingsService>();
    } catch (_) {
      settings = context.read<SettingsService>();
    }
    return L10n(settings.effectiveLanguage);
  }

  static const Map<String, String> languages = {
    'ar': 'العربية',
    'en': 'English',
    'de': 'Deutsch',
  };

  /// Language CHOICES for the settings picker — includes "follow the
  /// device language". The label is shown in the current UI language.
  Map<String, String> get languageChoices => {
        'system': call('langSystem'),
        'ar': 'العربية',
        'en': 'English',
        'de': 'Deutsch',
      };

  bool get isArabic => code == 'ar';

  String call(String key) => _data[code]?[key] ?? _data['ar']![key] ?? key;

  /// Arabic-Indic digits for the Arabic UI, Western digits otherwise.
  String number(int n) {
    if (!isArabic) return n.toString();
    const d = ['٠', '١', '٢', '٣', '٤', '٥', '٦', '٧', '٨', '٩'];
    return n.toString().split('').map((c) => d[int.parse(c)]).join();
  }

  /// Weekday name, Monday first (matching DateTime.weekday).
  String weekday(int weekday) => _weekdays[code]![weekday - 1];

  /// Gregorian month name, 1-based.
  String gregorianMonth(int month) => _gregorianMonths[code]![month - 1];

  /// Hijri month name, 1-based. Kept here rather than taken from the
  /// hijri package, which has no German.
  String hijriMonth(int month) => _hijriMonths[code]![month - 1];

  /// Era suffix written after the year.
  String get hijriEra => const {'ar': 'هـ', 'en': 'AH', 'de': 'AH'}[code]!;
  String get gregorianEra => const {'ar': 'م', 'en': '', 'de': ''}[code]!;

