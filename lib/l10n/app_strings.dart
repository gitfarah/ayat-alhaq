  const L10n(this.code);

  /// Rebuilds the caller whenever the (effective) language changes.
  static L10n of(BuildContext context) =>
      L10n(context.watch<SettingsService>().effectiveLanguage);

  static const Map<String, String> languages = {
    'ar': 'العربية',
    'en': 'English',
    'de': 'Deutsch',
  };

  /// Language CHOICES for the settings picker — includes "follow the
  /// device language". The label is shown in the current UI language.
  Map<String, String> get languageChoices => {
        'system': call('langSystem'),
        'ar': 'العربية',
        'en': 'English',
        'de': 'Deutsch',
      };

  bool get isArabic => code == 'ar';

  String call(String key) =>
      _data[code]?[key] ?? _data['ar']![key] ?? key;

  /// Arabic-Indic digits for the Arabic UI, Western digits otherwise.
  String number(int n) {
    if (!isArabic) return n.toString();
    const d = ['٠', '١', '٢', '٣', '٤', '٥', '٦', '٧', '٨', '٩'];
    return n.toString().split('').map((c) => d[int.parse(c)]).join();
  }

  /// Weekday name, Monday first (matching DateTime.weekday).
  String weekday(int weekday) => _weekdays[code]![weekday - 1];

  /// Gregorian month name, 1-based.
  String gregorianMonth(int month) => _gregorianMonths[code]![month - 1];

  /// Hijri month name, 1-based. Kept here rather than taken from the
  /// hijri package, which has no German.
  String hijriMonth(int month) => _hijriMonths[code]![month - 1];

